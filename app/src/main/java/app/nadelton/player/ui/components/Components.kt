@Composable
fun MiniPlayer(
    controller: MediaController?,
    onOpen: () -> Unit,
) {
    val state = rememberPlaybackUiState(controller)

    AnimatedVisibility(visible = state.hasItem && controller != null) {
        Surface(
            color = MaterialTheme.colorScheme.surfaceContainer,
            tonalElevation = 3.dp,
            modifier = Modifier
                .fillMaxWidth()
                .clickable(onClick = onOpen),
        ) {
            Row(
                modifier = Modifier.padding(horizontal = 12.dp, vertical = 8.dp),
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Artwork(
                    url = state.artworkUri,
                    modifier = Modifier.size(44.dp),
                    shape = RoundedCornerShape(9.dp),
                )
                Spacer(Modifier.width(12.dp))
                Column(Modifier.weight(1f)) {
                    Text(
                        text = state.title,
                        style = MaterialTheme.typography.titleMedium,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis,
                    )
                    Text(
                        text = state.artist,
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis,
                    )
                }
                IconButton(onClick = {
                    if (state.isPlaying) controller?.pause() else controller?.play()
                }) {
                    Icon(
                        imageVector = if (state.isPlaying) Icons.Rounded.Pause else Icons.Rounded.PlayArrow,
                        contentDescription = if (state.isPlaying) "Pause" else "Abspielen",
                    )
                }
                IconButton(onClick = { controller?.seekToNextMediaItem() }) {
                    Icon(Icons.Rounded.SkipNext, contentDescription = "Nächster Titel")
                }
            }
        }
    }
}

@Composable
fun HorizontalAlbumRow(
    albums: List<Album>,
    onOpenAlbum: (String) -> Unit,
    cardWidth: Dp = 150.dp,
) {
    androidx.compose.foundation.lazy.LazyRow(
        contentPadding = androidx.compose.foundation.layout.PaddingValues(horizontal = 16.dp),
        horizontalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        items(albums.size, key = { albums[it].id }) { index ->
            AlbumCard(
                album = albums[index],
                onClick = { onOpenAlbum(albums[index].id) },
                modifier = Modifier.width(cardWidth),
            )
        }
    }
}
